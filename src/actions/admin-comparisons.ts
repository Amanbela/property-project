export async function updateComparison(
  id: string,
  _prev: unknown,
  formData: FormData
) {
  if (!(await assertAdmin())) return { ok: false as const, error: "Unauthorized" };

  const raw = Object.fromEntries(formData.entries());

  const parsed = comparisonSchema.safeParse({
    area1: raw.area1,
    area2: raw.area2,
    isActive: raw.isActive === "true" || raw.isActive === "on",
    sortOrder: raw.sortOrder || 0,
    metaTitle: raw.metaTitle || undefined,
    metaDescription: raw.metaDescription || undefined,
    heroHeading: raw.heroHeading || undefined,
    introText: raw.introText || undefined,
    verdict: raw.verdict || undefined
  });

  if (!parsed.success) return { ok: false as const, error: parsed.error.flatten().fieldErrors };

  try {
    await connectForWrites();

    const update: Record<string, unknown> = {
      isActive: parsed.data.isActive,
      sortOrder: parsed.data.sortOrder
    };

    if (raw.metaTitle?.toString().trim()) update.metaTitle = raw.metaTitle.toString().trim();
    if (raw.metaDescription?.toString().trim()) update.metaDescription = raw.metaDescription.toString().trim();
    if (raw.heroHeading?.toString().trim()) update.heroHeading = raw.heroHeading.toString().trim();
    if (raw.introText?.toString().trim()) update.introText = raw.introText.toString().trim();
    if (raw.verdict?.toString().trim()) update.verdict = raw.verdict.toString().trim();

    await AreaComparisonModel.findByIdAndUpdate(id, { $set: update }).exec();

    revalidatePath("/comparisons");
    revalidatePath(`/comparisons/${raw.slug || id}`);
    revalidatePath("/admin/comparisons");
    return { ok: true as const };
  } catch (e) {
    return { ok: false as const, error: String(e) };
  }
}

export async function deleteComparison(id: string) {
  if (!(await assertAdmin())) return { ok: false as const, error: "Unauthorized" };
  await connectForWrites();
  await AreaComparisonModel.findByIdAndDelete(id).exec();
  revalidatePath("/comparisons");
  revalidatePath("/admin/comparisons");
  return { ok: true as const };
}

export async function getComparisons() {
  if (!(await assertAdmin())) return [];
  await connectForWrites();
  const docs = await AreaComparisonModel.find({})
    .populate("area1", "name slug")
    .populate("area2", "name slug")
    .sort({ sortOrder: 1 })
    .lean()
    .exec();
  return docs;
}

export async function getComparisonById(id: string) {
  if (!(await assertAdmin())) return null;
  await connectForWrites();
  const doc = await AreaComparisonModel.findById(id).lean().exec();
  return doc ?? null;
}

export async function autoGenerateComparisons(areaIds: string[]) {
  if (!(await assertAdmin())) return { ok: false as const, error: "Unauthorized" };

  await connectForWrites();
  let created = 0;
  let skipped = 0;
  const errors: string[] = [];

  const areas = await AreaModel.find({ _id: { $in: areaIds } })
    .select("name slug")
    .lean()
    .exec();

  const areaMap = new Map(areas.map((a) => [String(a._id), { name: a.name, slug: a.slug }]));

  for (let i = 0; i < areaIds.length; i++) {
    for (let j = i + 1; j < areaIds.length; j++) {
      const id1 = areaIds[i];
      const id2 = areaIds[j];

      try {
        const existing = await AreaComparisonModel.findOne({
          $or: [
            { area1: id1, area2: id2 },
            { area1: id2, area2: id1 }
          ]
        }).lean().exec();

        if (existing) {
          skipped++;
          continue;
        }

        const a1 = areaMap.get(id1);
        const a2 = areaMap.get(id2);

        if (!a1 || !a2) {
          errors.push(`Area not found for one of: ${id1}, ${id2}`);
          continue;
        }

        const slug = slugify(`${a1.slug}-vs-${a2.slug}`);

        await AreaComparisonModel.create({
          slug,
          area1: id1,
          area2: id2,
          isAutoGenerated: true,
          isActive: true,
          sortOrder: 0,
          heroHeading: `${a1.name} vs ${a2.name}: Which Area to Buy in Indore?`,
          metaTitle: `${a1.name} vs ${a2.name} Property Comparison | AreaMatch`,
          metaDescription: `Compare ${a1.name} and ${a2.name} — pricing, connectivity, schools, hospitals, and investment potential. Find the best area for your budget in Indore.`
        });

        created++;
      } catch (e) {
        errors.push(`Failed for pair (${id1}, ${id2}): ${String(e)}`);
      }
    }
  }

  revalidatePath("/admin/comparisons");
  return { ok: true as const, created, skipped, errors };
}
